def collect_hard_demotions(data):
    """返回需要从 hard canon 降到 reference 软提示的条目。"""
    out = {}
    loc = data.get("地点与区域")
    if isinstance(loc, dict):
        for k, v in loc.items():
            if (len(str(k).split()) >= 3
                    or _DEMOTE_LOC_RE.match(str(k))):
                out[("地点与区域", k)] = ("百科与术语", v)
    item = data.get("物品·武器·装备·神器")
    if isinstance(item, dict):
        for k, v in item.items():
            words = str(k).split()
            if (len(words) >= 5 or (len(words) == 1
                                    and _GENERIC_ITEM_RE.match(str(k)))
                    or ("物品·武器·装备·神器", k) in _EN_DEMOTE_KEYS):
                out[("物品·武器·装备·神器", k)] = ("百科与术语", v)
    for cat, key in _EN_DEMOTE_KEYS:
        table = data.get(cat)
        if isinstance(table, dict) and key in table and cat != "物品·武器·装备·神器":
            out[(cat, key)] = ("百科与术语", table[key])
    return out


